import { readFileSync, writeFileSync } from 'node:fs';
const chat = readFileSync(new URL('../ref/md files/ai_chat.md', import.meta.url), 'utf8');
const home = readFileSync(new URL('../ref/md files/home_decision.md', import.meta.url), 'utf8');
const content = '// Generated by npm run ai:prompts. Edit the source Markdown files.\n'
  + `export const chatPrompt = ${JSON.stringify(chat)};\nexport const homePrompt = ${JSON.stringify(home)};\n`;
const destination = new URL('../supabase/functions/_shared/prompts.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== content) throw new Error('Run npm run ai:prompts before deploying.');
} else writeFileSync(destination, content);
